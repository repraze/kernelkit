// Build kernelkit as a shadcn registry, so apps can `npx shadcn add @kernelkit/button` and own the code.
//
//   node scripts/build-registry.mjs            → packages/kernelkit/registry.json + registry/ sources
//   (then `shadcn build` turns it into packages/site/public/r/*.json, served by the docs site)
//
// The lib is written against its own package paths (`kernelkit/components/x`); registry copies are
// rewritten to the shadcn aliases a consumer's components.json resolves (`@/components/ui/x`, `@/lib/x`,
// `@/hooks/x`). The token CSS is bundled into one file (palette + shadcn mapping + kernelkit layer), since
// consumers then need no extra package.
import {mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync} from "node:fs";
import {basename, dirname, join, relative} from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const LIB = join(ROOT, "packages/kernelkit");
const SRC = join(LIB, "src");
const OUT = join(LIB, "registry/kernelkit");
const PALETTE = join(ROOT, "node_modules/@repraze/termicolor/dist");
const HOMEPAGE = "https://repraze.github.io/kernelkit";
const NS = "@kernelkit";
/** The package's own name: its sources import each other through it. */
const SELF = "@repraze/kernelkit";

const pkg = JSON.parse(readFileSync(join(LIB, "package.json"), "utf8"));
const versions = {...pkg.dependencies, ...pkg.peerDependencies};

const walk = (dir) =>
    readdirSync(dir).flatMap((f) => {
        const p = join(dir, f);
        return statSync(p).isDirectory() ? walk(p) : [p];
    });

/** Rewrite lib-internal imports to consumer aliases. */
function rewrite(src) {
    return src
        .replace(/(["'])@repraze\/kernelkit\/components\//g, "$1@/components/ui/")
        .replace(/(["'])@repraze\/kernelkit\/lib\//g, "$1@/lib/")
        .replace(/(["'])@repraze\/kernelkit\/hooks\//g, "$1@/hooks/")
        .replace(/(["'])@repraze\/kernelkit\/provider\1/g, "$1@/components/theme-provider$1")
        .replace(/(["'])\.\/theme\1/g, "$1@/lib/theme$1");
}

/** npm packages and registry items a source file imports. */
function scan(src) {
    const deps = new Set();
    const items = new Set();
    for (const [, spec] of src.matchAll(/from\s+["']([^"']+)["']|import\(\s*["']([^"']+)["']\s*\)/g)) {
        if (!spec) {
            continue;
        }
        if (spec.startsWith(`${SELF}/components/`)) {
            items.add(spec.slice(`${SELF}/components/`.length).split("/")[0]);
        } else if (spec.startsWith(`${SELF}/lib/`)) {
            const name = spec.slice(`${SELF}/lib/`.length);
            if (name !== "utils") {
                items.add(name);
            }
        } else if (spec.startsWith(`${SELF}/hooks/`)) {
            items.add(spec.slice(`${SELF}/hooks/`.length));
        } else if (spec === `${SELF}/provider`) {
            items.add("theme-provider");
        } else if (!spec.startsWith(".") && !spec.startsWith(SELF)) {
            const name = spec.startsWith("@") ? spec.split("/").slice(0, 2).join("/") : spec.split("/")[0];
            if (!["react", "react-dom", "@repraze/termicolor"].includes(name)) {
                deps.add(versions[name] ? `${name}@${versions[name]}` : name);
            }
        }
    }
    return {deps, items};
}

rmSync(join(LIB, "registry"), {recursive: true, force: true});
const items = [];

function emit(name, type, title, description, files, extra = {}) {
    const deps = new Set();
    const regs = new Set();
    const outFiles = files.map(({from, path, fileType, target}) => {
        const raw = readFileSync(from, "utf8");
        const {deps: d, items: r} = scan(raw);
        d.forEach((x) => deps.add(x));
        r.forEach((x) => x !== name && regs.add(`${NS}/${x}`));
        const dest = join(OUT, path);
        mkdirSync(dirname(dest), {recursive: true});
        writeFileSync(dest, from.endsWith(".css") ? raw : rewrite(raw));
        return {path: relative(LIB, dest), type: fileType, ...(target ? {target} : {})};
    });
    items.push({
        name,
        type,
        title,
        description,
        ...(deps.size ? {dependencies: [...deps].sort()} : {}),
        registryDependencies: [...new Set([...regs, ...(extra.registryDependencies ?? [])])].sort(),
        files: outFiles,
        ...(extra.docs ? {docs: extra.docs} : {}),
    });
}

// ── styles: one CSS file with every token ────────────────────────────────────────────────────────
const css = [
    "/* KernelKit tokens - generated by kernelkit/scripts/build-registry.mjs. Import after tailwindcss:",
    ' *     @import "tailwindcss";',
    ' *     @import "./kernelkit.css";',
    " */",
    '@import "tw-animate-css";',
    "",
    readFileSync(join(PALETTE, "palette.css"), "utf8"),
    readFileSync(join(PALETTE, "shadcn.css"), "utf8"),
    readFileSync(join(SRC, "styles/shadcn.css"), "utf8"),
    readFileSync(join(SRC, "styles/kernelkit.css"), "utf8")
        .replace(/^@import[^\n]*\n/gm, "")
        .replace(/^@source[^\n]*\n/gm, "")
        .replace(/^\/\* KernelKit's own class names live in its sources[^\n]*\n/m, ""),
].join("\n");
const cssPath = join(OUT, "styles/kernelkit.css");
mkdirSync(dirname(cssPath), {recursive: true});
writeFileSync(cssPath, css);
items.push({
    name: "styles",
    type: "registry:file",
    title: "KernelKit tokens",
    description: "TermiColor palette, shadcn token mapping, color axis, radius knob, field and code tokens.",
    dependencies: ["tw-animate-css"],
    registryDependencies: [],
    files: [{path: relative(LIB, cssPath), type: "registry:file", target: "~/styles/kernelkit.css"}],
    docs: 'Add `@import "./styles/kernelkit.css";` after `@import "tailwindcss";` in your global stylesheet.',
});

// ── lib, hooks, provider ─────────────────────────────────────────────────────────────────────────
const LIB_ITEMS = {
    color: ["Color axis", "The `color` × `variant` system: --c / --c-fill vars per color, resolveFill()."],
    recipes: ["Recipes", "Shared class recipes: focus ring, field surface, popup surface, list items…"],
    highlighter: ["Highlighter", "Shiki highlighter with a CSS-variables theme mapped to TermiColor syntax roles."],
};
for (const [name, [title, description]] of Object.entries(LIB_ITEMS)) {
    const file = name === "highlighter" ? "highlighter.tsx" : `${name}.ts`;
    emit(
        name,
        "registry:lib",
        title,
        description,
        [{from: join(SRC, "lib", file), path: `lib/${file}`, fileType: "registry:lib"}],
        {registryDependencies: name === "highlighter" ? [] : [`${NS}/styles`]},
    );
}
for (const file of readdirSync(join(SRC, "hooks"))) {
    const name = file.replace(/\.tsx?$/, "");
    emit(name, "registry:hook", name, `${name} hook`, [
        {from: join(SRC, "hooks", file), path: `hooks/${file}`, fileType: "registry:hook"},
    ]);
}
emit(
    "theme-provider",
    "registry:component",
    "Theme provider",
    "ThemeProvider, useTheme, ThemeScope (scoped themes; overlays portal into the scope) and ThemeScript.",
    [
        {from: join(SRC, "provider/theme.ts"), path: "lib/theme.ts", fileType: "registry:lib"},
        {
            from: join(SRC, "provider/theme-provider.tsx"),
            path: "components/theme-provider.tsx",
            fileType: "registry:component",
        },
    ],
    {registryDependencies: [`${NS}/styles`]},
);

// ── components ───────────────────────────────────────────────────────────────────────────────────
const compDir = join(SRC, "components");
const titleOf = (n) => n.replace(/(^|-)(\w)/g, (_, s, c) => (s ? " " : "") + c.toUpperCase());
for (const file of readdirSync(compDir).filter((f) => f.endsWith(".tsx"))) {
    const name = basename(file, ".tsx");
    const files = [{from: join(compDir, file), path: `ui/${file}`, fileType: "registry:ui"}];
    // components with a folder of parts (data-table/)
    try {
        for (const part of walk(join(compDir, name))) {
            const rel = relative(compDir, part);
            files.push({from: part, path: `ui/${rel}`, fileType: "registry:ui"});
        }
    } catch {
        // no folder
    }
    emit(name, "registry:ui", titleOf(name), `${titleOf(name)} component.`, files);
}

const registry = {
    $schema: "https://ui.shadcn.com/schema/registry.json",
    name: "kernelkit",
    homepage: HOMEPAGE,
    items: items.sort((a, b) => a.name.localeCompare(b.name)),
};
writeFileSync(join(LIB, "registry.json"), `${JSON.stringify(registry, null, 4)}\n`);
console.log(`registry.json: ${items.length} items`);
